"""Arabic vocabulary for the model router: Modern Standard Arabic and Egyptian Arabic.

The router's method does not change with the language: it still works out, clause by
clause, what is being asked and how heavy the technical signals are. This module only
supplies the Arabic words for the same concepts, so that a request written in Arabic,
or in the Arabic/English mix developers actually use, is read as carefully as an
English one.

Text is normalised before matching (`normalize`): diacritics and tatweel are removed
and the letter variants that are written inconsistently are unified
(أ إ آ -> ا, ى -> ي, ة -> ه). Every pattern below is written in that normalised form.

Arabic attaches prefixes to words (ال, و, ب, ل ...), so most patterns match a stem
anywhere in a word. Short words that would otherwise match inside other words are
wrapped with `word()`.
"""
from __future__ import annotations

import re

_STRIP = re.compile("[ً-ْٰـ]")   # tashkeel, dagger alef, tatweel
_UNIFY = str.maketrans({"أ": "ا", "إ": "ا", "آ": "ا",
                        "ٱ": "ا", "ى": "ي", "ة": "ه"})
_LETTER = "ء-ي"


def normalize(text):
    """Unify the spelling variants of Arabic text. Other text passes through unchanged."""
    return _STRIP.sub("", text).translate(_UNIFY)


def has_arabic(text):
    return bool(re.search("[%s]" % _LETTER, text or ""))


def word(pattern):
    """Match only as a whole word (optionally behind the usual one-letter prefixes)."""
    return "(?<![%s])(?:ال|لل|[وفبلك])?(?:%s)(?![%s])" % (_LETTER, pattern, _LETTER)


